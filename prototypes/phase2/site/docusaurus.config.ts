// Diagnostic-only thin adapter: suppress MDX body files from the second docs
// plugin's *site plugin reload* watcher. Rspack still watches imported MDX for
// HMR; structural files (_category_.json/sidebar) remain watched.
const previewDocsAdapter = async (context: any, options: any) => {
  const plugin = await contentDocsPlugin(context, options);
  const original = plugin.getPathsToWatch;
  if (typeof original === 'function') {
    plugin.getPathsToWatch = () => {
      const paths = original.call(plugin);
      console.info('[dsh-live-editor][diag] staging getPathsToWatch', {
        t: new Date().toISOString(),
        isArray: Array.isArray(paths),
        type: typeof paths,
        paths,
      });
      if (!Array.isArray(paths)) throw new Error('staging getPathsToWatch did not return an array');
      // Keep tags.yml and _category_ globs; only remove the doc-body glob.
      // The structural sentinel is watched whenever the preview channel is
      // enabled so one Host write can reload this docs plugin exactly once.
      const filtered = filterStagingWatchPaths(paths, {
        watchSentinel: previewChannelEnabled,
        sentinelPath: structureSentinelPath,
      });
      if (r2SentinelWanted && r2SentinelPath !== structureSentinelPath) return [...filtered, r2SentinelPath];
      return filtered;
    };
  }
  return plugin;
};
(previewDocsAdapter as any).validateOptions = validateDocsOptions;

const r2Shadow = readR2ShadowConfig(process.env);
// The preview docs instance always uses the staging watcher filter. Suppressing
// the site-plugin reload for doc bodies is now part of the default draft
// preview path, not an A2 experiment.
// One rollback switch for the whole preview channel. When set to 'off', the
// site, page channel, Host capability and client all use the safe degradation:
// editing/draft recovery stay available, live preview is disabled. Do not
// toggle only one end; restart site and DSH with the same value.
const previewChannelEnabled = process.env.DSH_LIVE_EDITOR_PREVIEW_CHANNEL !== 'off';
const suppressDocsWatch = previewChannelEnabled;
const r2SentinelWanted = r2Shadow.active || r2Shadow.experiment || process.env.DSH_DIAG_R2_SENTINEL === '1';
if (previewChannelEnabled) {
  try {
    // The watcher needs an existing path before the first structural save.
    fs.mkdirSync(path.dirname(structureSentinelPath), { recursive: true });
    if (!fs.existsSync(structureSentinelPath)) fs.writeFileSync(structureSentinelPath, '{}\n', { mode: 0o600 });
  } catch (error) {
    console.warn('[dsh-live-editor] could not create structure reload sentinel', error);
  }
}
if (r2SentinelWanted) {
  try {
    fs.mkdirSync(path.dirname(r2SentinelPath), { recursive: true });
    if (!fs.existsSync(r2SentinelPath)) fs.writeFileSync(r2SentinelPath, '{}\n', { mode: 0o600 });
  } catch (error) {
    console.warn('[dsh-live-editor] could not create R2 sentinel placeholder', error);
  }
}
const previewDocsPlugin = previewChannelEnabled
  ? [previewDocsAdapter, previewDocsOptions]
  : ['@docusaurus/plugin-content-docs', previewDocsOptions];

