// Docusaurus reloadSitePlugin serializes plugin options with JSON.stringify.
// rehype-katex mutates the shared katexOptions object into a circular KaTeX
// parse tree, so the second docs plugin must not carry that object directly.
// A function wrapper is skipped by JSON serialization; KaTeX still receives a
// fresh shallow options object for every compilation.
const previewKatex = () => (tree: any, file: any) => rehypeKatex(katexOptions)(tree, file);

